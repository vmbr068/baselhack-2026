from pathlib import Path
try:
    from .models import MCPServerConfig
except ImportError:
    from models import MCPServerConfig

GENERATED_DIR = Path(__file__).parent / "generated_servers"
GENERATED_DIR.mkdir(parents=True, exist_ok=True)

def generate_standalone_mcp_script(config: MCPServerConfig) -> Path:
    """
    Generates a standalone FastMCP Python script that can be executed directly
    via stdio (e.g. by Claude Desktop, Cursor, or Antigravity).
    """
    script_path = GENERATED_DIR / f"{config.server_id}.py"

    code = f'''# Generated by Dynamic MCP Creator for {config.hotel_name}
# Target URL: {config.target_url}

import asyncio
from mcp.server.fastmcp import FastMCP
from playwright.async_api import async_playwright

mcp = FastMCP("{config.hotel_name} Reservation MCP")
TARGET_URL = "{config.target_url}"

@mcp.tool()
async def check_availability(check_in: str, check_out: str, guests: int = 2) -> str:
    """
    Search hotel room availability on {config.hotel_name}.
    Dates must be in YYYY-MM-DD format.
    """
    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True)
        page = await browser.new_page()
        try:
            await page.goto(TARGET_URL, wait_until="domcontentloaded")
            await page.wait_for_timeout(1000)
            
            # Fill inputs
            try:
                await page.fill("#check-in", check_in)
                await page.fill("#check-out", check_out)
                await page.select_option("#guests", str(guests))
                await page.click("#btn-search-rooms")
                await page.wait_for_timeout(1500)
            except Exception as fill_err:
                pass

            # Extract available rooms
            rooms = await page.evaluate("""
                () => {{
                    const list = [];
                    document.querySelectorAll('.room-card, .room-item').forEach(c => {{
                        const title = c.querySelector('.room-title, h3')?.innerText?.trim();
                        const price = c.querySelector('.room-price, .price')?.innerText?.trim();
                        if (title) list.push(`${{title}} (${{price || 'Price on request'}}`);
                    }});
                    return list;
                }}
            """)
            
            if not rooms:
                return f"No rooms explicitly listed or please verify dates: {{check_in}} to {{check_out}}"
            return f"Available Rooms at {config.hotel_name}:\\n" + "\\n".join(f"- {{r}}" for r in rooms)
        finally:
            await browser.close()

@mcp.tool()
async def reserve_room(room_title: str, guest_name: str, guest_email: str, guest_phone: str = "", special_requests: str = "") -> str:
    """
    Reserve a specific room at {config.hotel_name} with guest details.
    """
    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True)
        page = await browser.new_page()
        try:
            await page.goto(TARGET_URL, wait_until="domcontentloaded")
            await page.wait_for_timeout(1000)
            
            # Click search or open rooms
            try:
                await page.click("#btn-search-rooms")
                await page.wait_for_timeout(1000)
            except Exception:
                pass

            # Click book button
            try:
                room_card = page.locator(f".room-card:has-text('{{room_title}}')").first
                if await room_card.is_visible():
                    await room_card.locator("button, .btn-book").first.click()
                else:
                    await page.locator(".btn-book, button:has-text('Reserve')").first.click()
            except Exception:
                await page.locator(".btn-book, button:has-text('Reserve')").first.click()

            await page.wait_for_timeout(800)

            # Fill guest details
            await page.fill("#guest-name", guest_name)
            await page.fill("#guest-email", guest_email)
            if guest_phone:
                try:
                    await page.fill("#guest-phone", guest_phone)
                except Exception:
                    pass

            # Submit
            await page.click("#btn-confirm-reservation, button[type='submit']")
            await page.wait_for_timeout(1500)

            conf_text = await page.evaluate("""
                () => {{
                    const el = document.querySelector('#confirmation-view, .confirmation-card');
                    return el ? el.innerText.trim() : 'Booking confirmed.';
                }}
            """)

            return f"Reservation Result: {{conf_text}}"
        finally:
            await browser.close()

if __name__ == "__main__":
    mcp.run()
'''

    with open(script_path, "w", encoding="utf-8") as f:
        f.write(code)

    return script_path
